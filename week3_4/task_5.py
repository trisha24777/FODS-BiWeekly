''' Calculator functions '''
def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return round(a / b, 2)

def truncated_div(a, b):
    return a // b

def modulus(a, b):
    return a % b

def exponentiate(a, b):
    return a ** b